@Composable
@ReadOnlyComposable
internal fun trx(text: String): String {
    if (LocalMarbleStrings.current.language != MarbleLanguage.FA) return text
    return faTranslate(text)
}

@Composable
@ReadOnlyComposable
internal fun trxOrNull(text: String?): String? = text?.let { trx(it) }

/**
 * MARBLE_PERSIAN_JOIN_V249 — every Persian sentence the app draws arrives through here, so this is
 * the one place the orthography rule is enforced at runtime. The dictionary is already normalized
 * in source (`tools/persian-normalize.py` proves it), which makes the pass a no-op for it; what it
 * still catches is the copy assembled at runtime — a live message, a template, a server name
 * glued to a Persian verb — where no source sweep can reach.
 */
internal fun faTranslate(text: String): String = PersianOrthography.normalize(faTranslateRaw(text))

/** Every Persian value the dictionary ships; the orthography test reads them all. */
internal fun faLexiconValues(): Collection<String> = FaEffectiveLexicon.values

private fun faTranslateRaw(text: String): String {
    if (text.isBlank()) return text
    FaEffectiveLexicon[text]?.let { return it }
    val trimmed = text.trim()
    if (trimmed !== text) FaEffectiveLexicon[trimmed]?.let { return text.replace(trimmed, it) }

    FaLexiconLower[trimmed.lowercase()]?.let { return it }
    faPattern(trimmed)?.let { return it }
    // MARBLE_PERSIAN_CONNECT_DOCK_COUNCIL_V233 — a live repository message is a known English
    // phrase glued to a server name or a number ("Fast connect • Berlin 01"). Translate the known
    // parts and leave the proper noun alone: V232's rule (never transliterate) still holds, but a
    // Persian screen no longer has to show an English verb in front of that name.
    val dynamic = faTranslateDynamic(trimmed)
    if (dynamic != trimmed) {
        return if (trimmed === text) dynamic else text.replace(trimmed, dynamic)
    }
    // Unknown copy must remain legible in its source language. Transliteration produced strings
    // that looked Persian but had no meaning; add a real phrase translation to FaLexicon instead.
    return text
}

